HEADER = "// Auto-generated by astbuilder gen-reflect - DO NOT EDIT\n"

#: Field type for each scalar kind: (FieldType enumerator, Value constructor).
_SCALAR = {
    TypeKind.Bool:    ("Bool",   "ofBool"),
    TypeKind.Int8:    ("I8",     "ofInt"),
    TypeKind.Int16:   ("I16",    "ofInt"),
    TypeKind.Int32:   ("I32",    "ofInt"),
    TypeKind.Int64:   ("I64",    "ofInt"),
    TypeKind.Uint8:   ("U8",     "ofUint"),
    TypeKind.Uint16:  ("U16",    "ofUint"),
    TypeKind.Uint32:  ("U32",    "ofUint"),
    TypeKind.Uint64:  ("U64",    "ofUint"),
    TypeKind.Float32: ("F32",    "ofFloat"),
    TypeKind.Float64: ("F64",    "ofFloat"),
    TypeKind.String:  ("String", "ofString"),
}


class GenReflectError(Exception):
    pass


class GenReflect(object):

    def __init__(self, outdir, namespace, license=None):
        self.outdir = outdir
        self.namespace = namespace.split("::") if namespace else []
        self.license = license
        self.ast = None
        self.cid = {}       # class name -> id (1-based)
        self.eid = {}       # enum/flags name -> index in the enum table
        self.sid = {}       # struct name -> index in the struct table

    # -- helpers ------------------------------------------------------------

    def _open(self):
        out = OutStream()
        out.println(HEADER.rstrip())
        if self.license is not None:
            out.println("/*")
            out.write(self.license.rstrip("\n"))
            out.println()
            out.println(" */")
        out.println()
        return out

    def _ns_enter(self, out):
        for n in self.namespace:
            out.println("namespace %s {" % n)
        out.println("namespace reflect {")
        out.println()

    def _ns_leave(self, out):
        out.println("} // namespace reflect")
        for n in reversed(self.namespace):
            out.println("} // namespace %s" % n)

    def _write(self, name, out):
        if not os.path.isdir(self.outdir):
            os.makedirs(self.outdir)
        # Always written: a build rule that runs this expects its outputs to
        # be newer than its inputs afterwards.
        with open(os.path.join(self.outdir, name), "w") as f:
            f.write(out.content())

    def _descendants(self, c):
        """`c` and every class deriving from it."""
        ret = []
        for d in self.ast.classes:
            a = d
            while a is not None:
                if a is c:
                    ret.append(d)
                    break
                a = a.super.target if a.super is not None else None
        return ret

    def _ftype(self, t):
        """(FieldType, target, owned) for a field or list element type."""
        if isinstance(t, TypeScalar):
            return _SCALAR[t.t][0], "0", "false"
        if isinstance(t, TypePointer):
            tgt = t.t.target if isinstance(t.t, TypeUserDef) else None
            if not isinstance(tgt, AstClass):
                raise GenReflectError("pointer to a non-class type %s" % getattr(t.t, "name", t.t))
            return "Node", "%d" % self.cid[tgt.name], \
                ("true" if t.pt in (PointerKind.Unique, PointerKind.Shared) else "false")
        if isinstance(t, TypeUserDef):
            tgt = t.target
            if isinstance(tgt, AstClass):
                return "Node", "%d" % self.cid[tgt.name], "false"
            if isinstance(tgt, AstEnum):
                return "Enum", "%d" % self.eid[tgt.name], "false"
            if isinstance(tgt, AstFlags):
                return "Flags", "%d" % self.eid[tgt.name], "false"
            if isinstance(tgt, AstStruct):
                return "Struct", "%d" % self.sid[tgt.name], "false"
            raise GenReflectError("unresolved user type %s" % t.name)
        if isinstance(t, TypeList):
            return "List", "0", "false"
        if isinstance(t, TypeMap):
            return "Map", "0", "false"
        raise GenReflectError("unhandled type %s" % type(t).__name__)

    def _value(self, t, expr, in_container):
        """A C++ expression making a `Value` from `expr`, of type `t`."""
        if isinstance(t, TypeScalar):
            ctor = _SCALAR[t.t][1]
            if t.t == TypeKind.String:
                return "Value::ofString(&(%s))" % expr
            return "Value::%s(%s)" % (ctor, expr)
        if isinstance(t, TypeList):
            # A list as a value: only a list of scalars (list<list<int32_t>>
            # elements), read with listSize()/listAt().
            if not isinstance(t.t, TypeScalar):
                raise GenReflectError("a list value must hold scalars")
            return "Value::ofList(&(%s), FieldType::%s)" % (expr, _SCALAR[t.t.t][0])
        if is_class_ref(t):
            ptr = expr
            if in_container and isinstance(t, TypePointer) and t.pt != PointerKind.Raw:
                ptr = "%s.get()" % expr
                if t.pt == PointerKind.Unique:
                    # A UP element can be non-owning: a borrowed node that
                    # another list owns, which is not a child here.
                    return "Value::ofNode(classify(%s), !%s.owned())" % (ptr, expr)
            return "Value::ofNode(classify(%s))" % ptr
        tgt = t.target
        if isinstance(tgt, AstEnum):
            return "Value::ofEnum(static_cast<int64_t>(%s), %d)" % (expr, self.eid[tgt.name])
        if isinstance(tgt, AstFlags):
            return "Value::ofFlags(static_cast<int64_t>(%s), %d)" % (expr, self.eid[tgt.name])
        if isinstance(tgt, AstStruct):
            return "Value::ofStruct(&(%s), %d)" % (expr, self.sid[tgt.name])
        raise GenReflectError("no value for %s" % type(t).__name__)

    # -- entry point --------------------------------------------------------

    def generate(self, ast):
        self.ast = ast
        self.cid = {c.name: i + 1 for i, c in enumerate(ast.classes)}
        enums = list(ast.enums) + list(ast.flags)
        self.eid = {e.name: i for i, e in enumerate(enums)}
        self.sid = {s.name: i for i, s in enumerate(ast.structs)}
        self.enums = enums
        self._gen_header()
        self._gen_source()

    # ======================================================================
    # Reflect.h
    # ======================================================================

    def _gen_header(self):
        out = self._open()
        out.println("#pragma once")
        out.println("#include <stdint.h>")
        out.println("#include <string>")
        out.println()
        for n in self.namespace:
            out.println("namespace %s {" % n)
        for c in self.ast.rootClasses():
            out.println("class I%s;" % c.name)
        for n in reversed(self.namespace):
            out.println("}")
        out.println()
        self._ns_enter(out)
        out.write('''/** Number of classes. Class ids are 1..NumClasses; 0 is "no node". */
constexpr uint16_t NumClasses = %(ncls)d;

/**
 * A node: its own class id, and the node as a pointer to that class's
 * interface. Cast `ptr` back only to `I<classes[kind].name> *`.
 */
struct Node {
    uint16_t    kind = 0;
    void        *ptr = nullptr;

    explicit operator bool() const { return ptr != nullptr; }
    bool operator==(const Node &o) const { return kind == o.kind && ptr == o.ptr; }
    bool operator!=(const Node &o) const { return !(*this == o); }
};

/** A field's type, or a list's element type. */
enum class FieldType : uint8_t {
    Bool, I8, U8, I16, U16, I32, U32, I64, U64, F32, F64, String,
    Enum, Flags, Struct, Node, List, Map
};

/**
 * A field value read through a getter. One payload member is meaningful,
 * chosen by `kind`; they share storage, so a getter writes two words, not
 * eight (the getters are most of this file's code).
 */
struct Value {
    enum class Kind : uint8_t { Absent, Bool, Int, Uint, Float, String, Enum, Flags, Struct, Node, List };

    Kind                kind = Kind::Absent;
    // Node, read from a list of owning pointers: this element does not own
    // its node (UP's owned() is false). A tool linking the AST may list a
    // node in a second place without owning it; it is not a child there.
    bool                borrowed = false;
    uint16_t            type = 0;           // Enum, Flags: enum index; Struct: struct index; List: element FieldType
    union {
        bool                b;
        int64_t             i;              // Int, Enum, Flags
        uint64_t            u;
        double              d;
        const std::string   *s;             // String: owned by the node
        const void          *st;            // Struct, List: owned by the node
        Node                n;              // Node: kind 0 for a null pointer
    };

    Value() : n() { }

    static Value ofBool(bool v) { Value r; r.kind = Kind::Bool; r.b = v; return r; }
    static Value ofInt(int64_t v) { Value r; r.kind = Kind::Int; r.i = v; return r; }
    static Value ofUint(uint64_t v) { Value r; r.kind = Kind::Uint; r.u = v; return r; }
    static Value ofFloat(double v) { Value r; r.kind = Kind::Float; r.d = v; return r; }
    static Value ofString(const std::string *v) { Value r; r.kind = Kind::String; r.s = v; return r; }
    static Value ofEnum(int64_t v, uint16_t t) { Value r; r.kind = Kind::Enum; r.i = v; r.type = t; return r; }
    static Value ofFlags(int64_t v, uint16_t t) { Value r; r.kind = Kind::Flags; r.i = v; r.type = t; return r; }
    static Value ofStruct(const void *v, uint16_t t) { Value r; r.kind = Kind::Struct; r.st = v; r.type = t; return r; }
    static Value ofNode(Node v, bool borrowed=false) {
        Value r; r.kind = Kind::Node; r.n = v; r.borrowed = borrowed; return r;
    }
    template <class T> static Value ofList(const T *v, FieldType elem) {
        Value r; r.kind = Kind::List; r.st = v; r.type = static_cast<uint16_t>(elem); return r;
    }
};

/** A List value (a list of scalars held as a list element): its size and elements. */
uint32_t listSize(const Value &list);
Value listAt(const Value &list, uint32_t idx);

/**
 * A field as declared on its class. `get` reads a non-list field; `size` and
 * `at` read a list. All three take the node's handle members, and are only
 * valid for a node of the declaring class or one deriving from it.
 */
struct FieldInfo {
    const char  *name;
    uint16_t    owner;      // the declaring class
    FieldType   type;
    FieldType   elem;       // List: the element type
    uint16_t    target;     // Node: the declared class; Enum, Flags: enum index; Struct: struct index
    bool        owned;      // Node: an owning pointer (a child) rather than a reference
    Value       (*get)(void *obj, uint16_t kind);
    uint32_t    (*size)(void *obj, uint16_t kind);
    Value       (*at)(void *obj, uint16_t kind, uint32_t idx);
};

struct ClassInfo {
    const char  *name;
    uint16_t    super;          // 0 for a root class
    uint16_t    firstField;     // index into fields[] of the first declared field
    uint16_t    numFields;      // declared here, not inherited
};

/** Enums and flags. An enum's value is its position; a flag's is 1 << position. */
struct EnumInfo {
    const char          *name;
    bool                flags;
    uint16_t            numValues;
    const char *const   *values;
};

struct StructFieldInfo {
    const char  *name;
    FieldType   type;
    uint16_t    target;         // Enum, Flags: enum index
    Value       (*get)(const void *st);
};

struct StructInfo {
    const char              *name;
    uint16_t                numFields;
    const StructFieldInfo   *fields;
};

extern const ClassInfo classes[NumClasses + 1];     // [0] is "no node"
extern const FieldInfo fields[];
extern const uint16_t  numFields;
extern const EnumInfo  enums[];
extern const uint16_t  numEnums;
extern const StructInfo structs[];
extern const uint16_t  numStructs;

''' % {"ncls": len(self.ast.classes)})
        out.println("/** The handle for any node; kind 0 for null. One virtual call. */")
        for c in self.ast.rootClasses():
            out.println("Node classify(I%s *n);" % c.name)
            out.println("/** The inverse of classify(): the node as an I%s, or null if it is not one. */" % c.name)
            out.println("I%s *as%s(const Node &n);" % (c.name, c.name))
        out.println()
        self._ns_leave(out)
        self._write("Reflect.h", out)

    # ======================================================================
    # Reflect.cpp
    # ======================================================================

    def _gen_source(self):
        out = self._open()
        out.println('#include "Reflect.h"')
        out.println("#include <vector>")
        out.println('#include "%s/IVisitor.h"' % "/".join(self.namespace))
        inc = "/".join(self.namespace)
        for e in self.enums:
            out.println('#include "%s/%s.h"' % (inc, e.name))
        for s in self.ast.structs:
            out.println('#include "%s/%s.h"' % (inc, s.name))
        for c in self.ast.classes:
            out.println('#include "%s/I%s.h"' % (inc, c.name))
        out.println()
        self._ns_enter(out)
        out.println("namespace {")
        out.println()
        out.println("// Out of line: getters of one class share its upcast switch rather than")
        out.println("// each inlining a copy (a base class's switch has a case per subclass).")
        out.println("#if defined(_MSC_VER)")
        out.println("#define REFLECT_NOINLINE __declspec(noinline)")
        out.println("#else")
        out.println("#define REFLECT_NOINLINE __attribute__((noinline))")
        out.println("#endif")
        out.println()
        self._gen_classifier(out)
        self._gen_upcasts(out)
        self._gen_getters(out)
        self._gen_struct_getters(out)
        out.println("} // namespace")
        out.println()
        self._gen_tables(out)
        self._gen_list_access(out)
        for c in self.ast.rootClasses():
            out.println("Node classify(I%s *n) {" % c.name)
            out.inc_indent()
            out.println("Classifier v;")
            out.println("if (n) {")
            out.inc_indent()
            out.println("n->accept(&v);")
            out.dec_indent()
            out.println("}")
            out.println("return v.node;")
            out.dec_indent()
            out.println("}")
            out.println()
            out.println("I%s *as%s(const Node &n) {" % (c.name, c.name))
            out.inc_indent()
            out.println("switch (n.kind) {")
            for d in self._descendants(c):
                out.println("case %d: return static_cast<I%s *>(n.ptr);" % (self.cid[d.name], d.name))
            out.println("default: return nullptr;")
            out.println("}")
            out.dec_indent()
            out.println("}")
            out.println()
        self._ns_leave(out)
        self._write("Reflect.cpp", out)

    def _gen_classifier(self, out):
        out.println("// The pure visitor: accept() calls exactly one of these, the node's own.")
        out.println("class Classifier : public virtual IVisitor {")
        out.println("public:")
        out.inc_indent()
        out.println("Node node;")
        for c in self.ast.classes:
            out.println("void visit%s(I%s *i) override { node.kind = %d; node.ptr = i; }" % (
                c.name, c.name, self.cid[c.name]))
        out.dec_indent()
        out.println("};")
        out.println()

    def _gen_upcasts(self, out):
        for c in self.ast.classes:
            if not c.data:
                continue
            out.println("REFLECT_NOINLINE I%s *as_%s(void *p, uint16_t k) {" % (c.name, c.name))
            out.inc_indent()
            out.println("switch (k) {")
            for d in self._descendants(c):
                out.println("case %d: return static_cast<I%s *>(p);" % (self.cid[d.name], d.name))
            out.println("default: return nullptr;")
            out.println("}")
            out.dec_indent()
            out.println("}")
            out.println()

    def _fn(self, c, d, what):
        return "%s_%s_%s" % (what, c.name, d.name)

    def _gen_getters(self, out):
        for c in self.ast.classes:
            for d in c.data:
                t = d.t
                node = "I%s *n = as_%s(p, k);" % (c.name, c.name)
                if isinstance(t, TypeList):
                    out.println("uint32_t %s(void *p, uint16_t k) {" % self._fn(c, d, "size"))
                    out.inc_indent()
                    out.println(node)
                    out.println("return n ? static_cast<uint32_t>(n->%s().size()) : 0;" % getter(d))
                    out.dec_indent()
                    out.println("}")
                    out.println("Value %s(void *p, uint16_t k, uint32_t i) {" % self._fn(c, d, "at"))
                    out.inc_indent()
                    out.println(node)
                    out.println("if (!n || i >= n->%s().size()) { return Value(); }" % getter(d))
                    out.println("return %s;" % self._value(t.t, "n->%s()[i]" % getter(d), True))
                    out.dec_indent()
                    out.println("}")
                elif isinstance(t, TypeMap):
                    continue
                else:
                    out.println("Value %s(void *p, uint16_t k) {" % self._fn(c, d, "get"))
                    out.inc_indent()
                    out.println(node)
                    out.println("if (!n) { return Value(); }")
                    out.println("return %s;" % self._value(t, "n->%s()" % getter(d), False))
                    out.dec_indent()
                    out.println("}")
                out.println()

    def _gen_struct_getters(self, out):
        for s in self.ast.structs:
            for d in s.data:
                out.println("Value sget_%s_%s(const void *p) {" % (s.name, d.name))
                out.inc_indent()
                out.println("const %s *s = static_cast<const %s *>(p);" % (s.name, s.name))
                out.println("return %s;" % self._value(d.t, "s->%s" % d.name, False))
                out.dec_indent()
                out.println("}")
        out.println()

    def _gen_list_access(self, out):
        cases = [
            ("Bool", "bool", "ofBool"), ("I8", "int8_t", "ofInt"), ("U8", "uint8_t", "ofUint"),
            ("I16", "int16_t", "ofInt"), ("U16", "uint16_t", "ofUint"),
            ("I32", "int32_t", "ofInt"), ("U32", "uint32_t", "ofUint"),
            ("I64", "int64_t", "ofInt"), ("U64", "uint64_t", "ofUint"),
            ("F32", "float", "ofFloat"), ("F64", "double", "ofFloat"),
        ]
        for fn, body in (("size", "return static_cast<uint32_t>(static_cast<const std::vector<%s> *>(l.st)->size());"),
                         ("at", "{ const std::vector<%s> &v = *static_cast<const std::vector<%s> *>(l.st);"
                                " return (i < v.size()) ? Value::%s(v[i]) : Value(); }")):
            if fn == "size":
                out.println("uint32_t listSize(const Value &l) {")
            else:
                out.println("Value listAt(const Value &l, uint32_t i) {")
            out.inc_indent()
            out.println("if (l.kind != Value::Kind::List) { return %s; }" % ("0" if fn == "size" else "Value()"))
            out.println("switch (static_cast<FieldType>(l.type)) {")
            for ft, ct, ctor in cases:
                if fn == "size":
                    out.println("case FieldType::%s: %s" % (ft, body % ct))
                else:
                    out.println("case FieldType::%s: %s" % (ft, body % (ct, ct, ctor)))
            if fn == "size":
                out.println("case FieldType::String: return static_cast<uint32_t>("
                            "static_cast<const std::vector<std::string> *>(l.st)->size());")
                out.println("default: return 0;")
            else:
                out.println("case FieldType::String: { const std::vector<std::string> &v = "
                            "*static_cast<const std::vector<std::string> *>(l.st);"
                            " return (i < v.size()) ? Value::ofString(&v[i]) : Value(); }")
                out.println("default: return Value();")
            out.println("}")
            out.dec_indent()
            out.println("}")
            out.println()

    def _gen_tables(self, out):
        # Classes
        out.println("const ClassInfo classes[NumClasses + 1] = {")
        out.inc_indent()
        out.println('{"", 0, 0, 0},')
        idx = 0
        self.first = {}
        for c in self.ast.classes:
            sup = c.super.target if c.super is not None else None
            out.println('{"%s", %d, %d, %d},' % (
                c.name, self.cid[sup.name] if sup is not None else 0, idx, len(c.data)))
            self.first[c.name] = idx
            idx += len(c.data)
        out.dec_indent()
        out.println("};")
        out.println()

        # Fields
        out.println("const FieldInfo fields[] = {")
        out.inc_indent()
        n = 0
        for c in self.ast.classes:
            for d in c.data:
                ft, tgt, owned = self._ftype(d.t)
                et = "Bool"
                get = size = at = "nullptr"
                if isinstance(d.t, TypeList):
                    et, tgt, owned = self._ftype(d.t.t)
                    size = self._fn(c, d, "size")
                    at = self._fn(c, d, "at")
                elif not isinstance(d.t, TypeMap):
                    get = self._fn(c, d, "get")
                out.println('{"%s", %d, FieldType::%s, FieldType::%s, %s, %s, %s, %s, %s},' % (
                    d.name, self.cid[c.name], ft, et, tgt, owned, get, size, at))
                n += 1
        if n == 0:
            out.println('{"", 0, FieldType::Bool, FieldType::Bool, 0, false, nullptr, nullptr, nullptr},')
        out.dec_indent()
        out.println("};")
        out.println("const uint16_t numFields = %d;" % n)
        out.println()

        # Enums and flags
        for i, e in enumerate(self.enums):
            names = [v[0] if isinstance(v, tuple) else v for v in e.values]
            out.println("const char *const enum%d_values[] = {%s};" % (
                i, ", ".join('"%s"' % v for v in names) or '""'))
        out.println("const EnumInfo enums[] = {")
        out.inc_indent()
        for i, e in enumerate(self.enums):
            out.println('{"%s", %s, %d, enum%d_values},' % (
                e.name, "true" if isinstance(e, AstFlags) else "false", len(e.values), i))
        if not self.enums:
            out.println('{"", false, 0, nullptr},')
        out.dec_indent()
        out.println("};")
        out.println("const uint16_t numEnums = %d;" % len(self.enums))
        out.println()

        # Structs
        for s in self.ast.structs:
            out.println("const StructFieldInfo struct_%s_fields[] = {" % s.name)
            out.inc_indent()
            for d in s.data:
                ft, tgt, _ = self._ftype(d.t)
                out.println('{"%s", FieldType::%s, %s, sget_%s_%s},' % (d.name, ft, tgt, s.name, d.name))
            out.dec_indent()
            out.println("};")
        out.println("const StructInfo structs[] = {")
        out.inc_indent()
        for s in self.ast.structs:
            out.println('{"%s", %d, struct_%s_fields},' % (s.name, len(s.data), s.name))
        if not self.ast.structs:
            out.println('{"", 0, nullptr},')
        out.dec_indent()
        out.println("};")
        out.println("const uint16_t numStructs = %d;" % len(self.ast.structs))
        out.println()
