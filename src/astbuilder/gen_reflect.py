'''
Reflection backend: field access by name, for code that does not know the
schema at compile time.

    Reflect.h / Reflect.cpp     C++: class, field, enum and struct tables, a
                                getter per field, and a classifier

Written for an expression language over the AST (pssparser's lint engine
evaluates rule predicates such as `node.lhs.op == ExprBinOp.BinOp_Eq`), which
must find a field from its name and read it from a node whose class it learns
at run time.


The handle
----------

A node is a `Node{kind, ptr}`: its own class id, and a `void *` that is the
node as a pointer to *that* class's interface (`IExprBin *` for an ExprBin).
`classify()` makes one with a single virtual call: it is an `IVisitor`, and
`accept()` lands in the visit method of the node's own class -- the pure
visitor, not the generated base visitor, which would chain up the hierarchy
and descend into children.

The pointer must be the most-derived interface, and must only ever be cast
back to exactly that type. The classes inherit `public virtual`, so one
object seen as `IExpr *` and as `IExprBin *` has two addresses; a `void *`
taken from one and cast to the other is wrong, and nothing would say so. That
is why every getter goes through `as_<Class>()`, a switch from the node's
kind to its own interface type and from there, by an ordinary implicit
upcast, to the field's declaring class. The switch has one case per class
deriving from the declaring class, so the total is the number of
(class, ancestor) pairs, a few hundred.

It also makes identity simple: two handles are the same node exactly when
both members are equal.


Why a getter per *declared* field
---------------------------------

A field inherited by thirty classes has one getter, not thirty. Flattened, the
pssparser schema has about seven times as many fields as it declares, and the
WASM build pays for every function emitted (pssparser lint-core-plan.md risk
R-1). The consumer flattens at load time by walking `super`.


Ids
---

Class ids are 1-based positions in `ast.classes`, the order the C++ backend
emits IVisitor's methods in. pssparser's `NodeKind::Id` is generated from
those methods in the same order, so the two agree; the consumer checks it.


What it does not cover
----------------------

Map fields are described (name, type) but have no getter: nothing that reads
a map by key is needed yet, and enumerating an unordered_map in a stable order
costs a sort per read. Their `get` returns an absent value.
'''

