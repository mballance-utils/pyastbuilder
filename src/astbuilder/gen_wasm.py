'''
WASM-boundary backend: emits the two halves of the AST wire format.

    AstSerializer.h / .cpp    C++: AST -> flat buffer
    deserialize.ts            TS:  flat buffer -> gen-ts classes

The two halves are generated together, from one schema, in one run. That is the
whole point: a serializer and a deserializer that disagree about field order put
values in the wrong slots and every downstream symptom is baffling. Generating
them separately is how that happens.

The schema hash is NOT emitted here, even though `wasm-core-plan.md` §3.3 lists
it as this backend's output. It is produced by `pssparser/scripts/gen_schema_hash.py`,
which already runs in the WASM CMake configure step and the TS build, and it
does not depend on the wire format -- it knows only the schema's identity.
Emitting it from here as well would mean two producers of one file, which is
the failure mode the hash exists to catch.


The wire format
---------------

    u32   magic          0x50535331
    u32   nodeCount
    u16 x nodeCount      class tag, one per node, in id order
    ...   bodies         each node's fields, in id order
    u32   magic          repeated, so truncation is caught at the end

Node ids are assigned by a pre-order walk of the *ownership* graph -- UP<T>
fields, and containers whose element type is UP<T>. The root is id 0. Every
reference (owning or not) is written as an i32 id, with -1 for null and for a
raw pointer whose target is not in the serialised graph.

Bodies are emitted in id order because the tag table is written first, which
lets the reader construct every node before any field is filled. There is no
fixup pass and no forward-reference bookkeeping on either side.

Not versioned. The schema hash makes versioning unnecessary -- the two ends
ship together and a mismatch is a load-time error, not a decoding problem.


Why two visitors rather than a node list
----------------------------------------

The C++ half is a pair of generated IVisitor implementations that perform the
*same* walk: the indexer assigns an id and recurses, the writer emits a body and
recurses. Body k therefore lands at id k with nothing recorded between the two
passes except the id map.

The alternative -- index into a `std::vector<node*>` and iterate it -- needs a
common pointer type for dispatch, and this hierarchy has none: 15 unrelated
roots, and the generated classes use virtual multiple inheritance, so an
upcast pointer is not even a stable identity. (That last point is why the id
map is keyed on `dynamic_cast<void*>`, which yields the most-derived address.)
'''

import os

from .ast_class import AstClass
from .ast_enum import AstEnum
from .ast_flags import AstFlags
from .ast_struct import AstStruct
